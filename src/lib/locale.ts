export type MessageKey = keyof typeof ZH;

const DICT: Record<Locale, Record<MessageKey, string>> = {
  "zh-Hant": ZH,
  en: EN,
};

export function detectLocale(input: {
  language?: string | null;
  onboarded?: boolean;
  stored?: string | null;
}): Locale {
  if (input.stored === "zh-Hant" || input.stored === "en") return input.stored;
  if (input.onboarded) return "zh-Hant";
  const lang = (input.language ?? "").toLowerCase();
  if (!lang || lang.startsWith("zh")) return "zh-Hant";
  return "en";
}

export function resolveLocale(locale: Locale | null | undefined): Locale {
  return locale === "en" ? "en" : "zh-Hant";
}

export function isMessageKey(value: string): value is MessageKey {
  return Object.prototype.hasOwnProperty.call(ZH, value);
}

export function t(locale: Locale | null | undefined, key: MessageKey, vars?: Record<string, string | number>): string {
  const lang = resolveLocale(locale);
  let out = DICT[lang][key] ?? ZH[key];
  if (vars) {
    for (const [name, value] of Object.entries(vars)) {
      out = out.replaceAll(`{${name}}`, String(value));
    }
  }
  return out;
}

export function countLabel(locale: Locale | null | undefined, n: number, one: MessageKey, many: MessageKey): string {
  const lang = resolveLocale(locale);
  return t(lang, lang === "en" && n === 1 ? one : many, { n });
}

export function localizeNotice(locale: Locale | null | undefined, value: string | null | undefined): string {
  if (!value) return "";
  return isMessageKey(value) ? t(locale, value) : value;
}

export function htmlLang(locale: Locale | null | undefined): string {
  return resolveLocale(locale) === "en" ? "en" : "zh-Hant-TW";
}
